export function getSeedTracks(countryCode: string, year: number): Track[] | null {
  const key = `${countryCode}-${year}`;
  if (SEED_TRACKS[key]) return SEED_TRACKS[key];

  const prefix = `${countryCode}-`;
  const matchingKeys = Object.keys(SEED_TRACKS).filter((k) => k.startsWith(prefix));
  if (matchingKeys.length === 0) {
    return null;
  }

  let closestKey = matchingKeys[0];
  let minDiff = 9999;
  for (const k of matchingKeys) {
    const kYear = Number(k.split('-')[1]);
    const diff = Math.abs(kYear - year);
    if (diff < minDiff) {
      minDiff = diff;
      closestKey = k;
    }
  }

  return SEED_TRACKS[closestKey] || null;
}
